// Interface languages for the app shell. Song (learning) languages are a
// separate setting and arrive with the language picker in step 9.

export const UI_LANGUAGES = ["en", "fr", "he", "es", "uk", "ru", "de", "ar"] as const;
export type UiLanguage = (typeof UI_LANGUAGES)[number];

export const DEFAULT_LANGUAGE: UiLanguage = "en";

export const RTL_LANGUAGES: readonly UiLanguage[] = ["he", "ar"];

export function directionOf(lang: UiLanguage): "ltr" | "rtl" {
  return RTL_LANGUAGES.includes(lang) ? "rtl" : "ltr";
}

export function isUiLanguage(value: unknown): value is UiLanguage {
  return typeof value === "string" && (UI_LANGUAGES as readonly string[]).includes(value);
}

/** First supported language in the device's preference list, e.g. ["he-IL", "en"] → "he". */
export function languageFromDevice(preferred: readonly string[]): UiLanguage {
  for (const tag of preferred) {
    const base = tag.toLowerCase().split("-")[0];
    if (base === "iw") return "he"; // legacy code for Hebrew
    if (isUiLanguage(base)) return base;
  }
  return DEFAULT_LANGUAGE;
}

/** Fills `{name}` placeholders: format("Saved: {n}", { n: 3 }) → "Saved: 3". */
export function format(template: string, values: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (match, name: string) => (name in values ? String(values[name]) : match));
}

